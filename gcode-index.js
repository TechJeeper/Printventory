'use strict';

const fs = require('fs');
const path = require('path');

const SLICED_EXTS = new Set(['.gcode', '.bgcode', '.3mf']);

function ensureSchema(db) {
  db.prepare(`
    CREATE TABLE IF NOT EXISTS sliced_files (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      model_id INTEGER,
      filePath TEXT NOT NULL UNIQUE,
      meta_json TEXT,
      created_at DATETIME NOT NULL DEFAULT (datetime('now')),
      FOREIGN KEY (model_id) REFERENCES models(id) ON DELETE SET NULL
    )
  `).run();
  db.prepare('CREATE INDEX IF NOT EXISTS idx_sliced_files_model ON sliced_files(model_id)').run();
}

/**
 * Parse common slicer header comments from G-code text.
 */
function parseGcodeHeader(text) {
  const src = String(text || '').slice(0, 64 * 1024);
  const meta = {
    estimatedTimeSec: null,
    filamentGrams: null,
    layerHeight: null,
    nozzleTemp: null,
    slicer: null
  };

  const slicerMatch = src.match(/;\s*(?:generated by\s+)?(PrusaSlicer|SuperSlicer|OrcaSlicer|Cura|BambuStudio|Simplify3D)\b/i);
  if (slicerMatch) meta.slicer = slicerMatch[1];

  const timePatterns = [
    /;\s*estimated printing time[^=:\n]*[:=]\s*(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?/i,
    /;\s*TIME:\s*(\d+)/i,
    /;\s*total estimated time[:=]\s*(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?/i
  ];
  for (const re of timePatterns) {
    const m = src.match(re);
    if (!m) continue;
    if (/TIME:\\s\*/.test(re.source) || re.source.includes('TIME:')) {
      // Cura-style ;TIME:8100 — only one capture group
      if (m.length === 2) {
        meta.estimatedTimeSec = Number(m[1]) || null;
        break;
      }
    }
    if (re.source.includes('TIME:')) {
      meta.estimatedTimeSec = Number(m[1]) || null;
      break;
    }
    const days = Number(m[1]) || 0;
    const hours = Number(m[2]) || 0;
    const mins = Number(m[3]) || 0;
    const secs = Number(m[4]) || 0;
    // total estimated time pattern has no days group
    const total = re.source.includes('total estimated')
      ? (Number(m[1]) || 0) * 3600 + (Number(m[2]) || 0) * 60 + (Number(m[3]) || 0)
      : days * 86400 + hours * 3600 + mins * 60 + secs;
    if (total > 0) {
      meta.estimatedTimeSec = total;
      break;
    }
  }

  const gramPatterns = [
    /;\s*filament used\s*\[g\]\s*=\s*([\d.]+)/i,
    /;\s*total filament used \[g\]\s*=\s*([\d.]+)/i,
    /;\s*filament used:\s*([\d.]+)\s*g/i
  ];
  for (const re of gramPatterns) {
    const m = src.match(re);
    if (m) {
      meta.filamentGrams = Number(m[1]);
      break;
    }
  }

  const layer = src.match(/;\s*layer_height\s*=\s*([\d.]+)/i)
    || src.match(/;\s*Layer height:\s*([\d.]+)/i);
  if (layer) meta.layerHeight = Number(layer[1]);

  const nozzle = src.match(/;\s*nozzle_temperature\s*=\s*([\d.]+)/i)
    || src.match(/;\s*nozzle temperature\s*=\s*([\d.]+)/i)
    || src.match(/M104\s+S([\d.]+)/i);
  if (nozzle) meta.nozzleTemp = Number(nozzle[1]);

  return meta;
}

function findSlicedFilesBeside(modelPath, { readdirSync = fs.readdirSync, statSync = fs.statSync } = {}) {
  const filePath = String(modelPath || '');
  if (!filePath || filePath.includes('::')) return [];
  let dir;
  try {
    dir = path.dirname(filePath);
  } catch (_) {
    return [];
  }
  let entries;
  try {
    entries = readdirSync(dir);
  } catch (_) {
    return [];
  }
  const base = path.basename(filePath, path.extname(filePath)).toLowerCase();
  const out = [];
  for (const name of entries) {
    const ext = path.extname(name).toLowerCase();
    if (!SLICED_EXTS.has(ext)) continue;
    const full = path.join(dir, name);
    try {
      if (!statSync(full).isFile()) continue;
    } catch (_) {
      continue;
    }
    const nbase = path.basename(name, ext).toLowerCase();
    if (nbase === base || nbase.startsWith(base) || base.startsWith(nbase)) {
      out.push(full);
    }
  }
  return out;
}

function upsertSlicedFile(db, { modelId = null, filePath, meta = {}, forceModelId = false } = {}) {
  const fp = String(filePath || '');
  if (!fp) throw new Error('filePath required');
  const modelIdSql = forceModelId
    ? 'model_id = excluded.model_id'
    : 'model_id = COALESCE(excluded.model_id, sliced_files.model_id)';
  db.prepare(`
    INSERT INTO sliced_files (model_id, filePath, meta_json)
    VALUES (?, ?, ?)
    ON CONFLICT(filePath) DO UPDATE SET
      ${modelIdSql},
      meta_json = excluded.meta_json
  `).run(modelId, fp, JSON.stringify(meta || {}));
}

function isAttachableGcodePath(filePath) {
  return /\.(gcode|bgcode)$/i.test(String(filePath || ''));
}

/**
 * Manually associate a .gcode / .bgcode file with a model (any folder).
 */
function attachGcode(db, modelId, gcodePath, { readFileSync = fs.readFileSync, existsSync = fs.existsSync } = {}) {
  ensureSchema(db);
  const id = Number(modelId);
  if (!Number.isInteger(id) || id <= 0) throw new Error('Invalid model id');
  const fp = path.normalize(String(gcodePath || ''));
  if (!fp || !isAttachableGcodePath(fp)) {
    throw new Error('Only .gcode or .bgcode files can be attached');
  }
  if (typeof existsSync === 'function' && !existsSync(fp)) {
    throw new Error('G-code file not found');
  }
  let meta = {};
  if (/\.gcode$/i.test(fp)) {
    try {
      meta = parseGcodeHeader(readFileSync(fp, 'utf8'));
    } catch (_) { /* ignore header parse errors */ }
  }
  upsertSlicedFile(db, { modelId: id, filePath: fp, meta, forceModelId: true });
  return {
    ok: true,
    modelId: id,
    filePath: fp,
    meta,
    files: listForModel(db, id)
  };
}

function detachGcode(db, modelId, gcodePath) {
  ensureSchema(db);
  const id = Number(modelId);
  const fp = String(gcodePath || '');
  if (!Number.isInteger(id) || id <= 0 || !fp) return { ok: false, removed: 0 };
  const result = db.prepare(
    'DELETE FROM sliced_files WHERE model_id = ? AND filePath = ?'
  ).run(id, fp);
  return { ok: true, removed: result.changes, files: listForModel(db, id) };
}

function listForModel(db, modelId) {
  return db.prepare(`
    SELECT id, model_id, filePath, meta_json, created_at
    FROM sliced_files WHERE model_id = ?
    ORDER BY filePath
  `).all(modelId).map((row) => {
    let meta = {};
    try { meta = JSON.parse(row.meta_json || '{}'); } catch (_) { meta = {}; }
    return { ...row, meta };
  });
}

function indexForModel(db, modelId, modelPath, fsApi) {
  const files = findSlicedFilesBeside(modelPath, fsApi);
  for (const fp of files) {
    let meta = {};
    if (/\.gcode$/i.test(fp)) {
      try {
        const text = fs.readFileSync(fp, 'utf8');
        meta = parseGcodeHeader(text);
      } catch (_) { /* ignore */ }
    }
    upsertSlicedFile(db, { modelId, filePath: fp, meta });
  }
  return listForModel(db, modelId);
}

function resolveMoonrakerBase(printer) {
  if (!printer) return null;
  const moonrakerUrl = printer.moonrakerUrl || printer.moonraker_url || null;
  const webUrl = printer.web_url || printer.webUrl || null;
  const host = printer.host || null;
  let baseRaw = moonrakerUrl || null;
  if (!baseRaw && printer.is_klipper) {
    baseRaw = webUrl || (host ? `http://${host}:7125` : null);
  } else if (!baseRaw && host) {
    baseRaw = `http://${host}:7125`;
  }
  if (!baseRaw) return null;
  let base = String(baseRaw).replace(/\/$/, '');
  if (!/^https?:\/\//i.test(base)) base = `http://${base}`;
  // Prefer Moonraker port when only a Mainsail/Fluidd origin was stored
  try {
    const u = new URL(base);
    if (!u.port || u.port === '80' || u.port === '443') {
      // keep as-is; many proxies expose /server on 80
    }
  } catch (_) {
    return null;
  }
  return base;
}

/**
 * Upload a sliced file to Moonraker (multipart POST /server/files/upload).
 */
async function sendToPrinter(printer, slicedFilePath, deps = {}) {
  if (!printer) return { ok: false, reason: 'not configured' };
  const filePath = String(slicedFilePath || '');
  if (!filePath) return { ok: false, reason: 'missing file' };

  const base = resolveMoonrakerBase(printer);
  if (!base) return { ok: false, reason: 'not configured' };

  const fetchFn = deps.fetch || global.fetch;
  const readFile = deps.readFile || ((p) => fs.promises.readFile(p));
  const FormDataCtor = deps.FormData || global.FormData;
  const BlobCtor = deps.Blob || global.Blob;

  if (typeof fetchFn !== 'function') {
    return { ok: false, reason: 'not configured', filePath, base };
  }

  try {
    const infoResp = await fetchFn(`${base}/server/info`, { method: 'GET' });
    if (!infoResp || !infoResp.ok) return { ok: false, reason: 'printer unreachable', filePath, base };
  } catch (_) {
    return { ok: false, reason: 'printer unreachable', filePath, base };
  }

  if (typeof FormDataCtor !== 'function' || typeof BlobCtor !== 'function') {
    return { ok: false, reason: 'upload unavailable', detail: 'FormData/Blob not available', filePath, base };
  }

  let bytes;
  try {
    bytes = await readFile(filePath);
  } catch (err) {
    return { ok: false, reason: 'file read failed', detail: err.message, filePath, base };
  }

  const fileName = path.basename(filePath);
  const form = new FormDataCtor();
  form.append('file', new BlobCtor([bytes]), fileName);
  form.append('root', 'gcodes');

  try {
    const uploadResp = await fetchFn(`${base}/server/files/upload`, {
      method: 'POST',
      body: form
    });
    if (!uploadResp || !uploadResp.ok) {
      const status = uploadResp ? uploadResp.status : 0;
      let detail = `HTTP ${status}`;
      try {
        const body = await uploadResp.text();
        if (body) detail = body.slice(0, 200);
      } catch (_) { /* ignore */ }
      return { ok: false, reason: 'upload failed', detail, filePath, base, fileName };
    }
    let result = null;
    try { result = await uploadResp.json(); } catch (_) { /* ignore */ }
    return { ok: true, filePath, base, fileName, result };
  } catch (err) {
    return { ok: false, reason: 'upload failed', detail: err.message, filePath, base };
  }
}

