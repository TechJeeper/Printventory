'use strict';

const assert = require('assert');
const path = require('path');
const { parseGcodeHeader, findSlicedFilesBeside } = require('./gcode-index');

function test(name, fn) {
  try {
    fn();
    console.log(`ok ${name}`);
  } catch (err) {
    console.error(`FAIL ${name}:`, err.message);
    process.exitCode = 1;
  }
}

test('parses PrusaSlicer-style header', () => {
  const text = `; generated by PrusaSlicer 2.6
; estimated printing time (normal mode) = 1h 12m 5s
; filament used [g] = 24.5
; layer_height = 0.2
; nozzle_temperature = 215
G1 X0
`;
  const meta = parseGcodeHeader(text);
  assert.equal(meta.slicer, 'PrusaSlicer');
  assert.equal(meta.estimatedTimeSec, 1 * 3600 + 12 * 60 + 5);
  assert.equal(meta.filamentGrams, 24.5);
  assert.equal(meta.layerHeight, 0.2);
  assert.equal(meta.nozzleTemp, 215);
});

test('parses Cura TIME seconds', () => {
  const meta = parseGcodeHeader(';TIME:3661\nG0');
  assert.equal(meta.estimatedTimeSec, 3661);
});

test('findSlicedFilesBeside matches sibling gcode', () => {
  const files = {
    'C:/lib': ['benchy.stl', 'benchy.gcode', 'other.3mf']
  };
  const found = findSlicedFilesBeside('C:/lib/benchy.stl', {
    readdirSync: (dir) => files[dir] || [],
    statSync: () => ({ isFile: () => true })
  });
  assert.ok(found.some((p) => /benchy\.gcode$/i.test(p.replace(/\\/g, '/'))));
});

test('attachGcode links file to model and parses header', () => {
  const Database = require('better-sqlite3');
  const { attachGcode, listForModel, ensureSchema } = require('./gcode-index');
  const db = new Database(':memory:');
  db.exec(`CREATE TABLE models (id INTEGER PRIMARY KEY, fileName TEXT)`);
  db.prepare('INSERT INTO models (fileName) VALUES (?)').run('benchy.stl');
  ensureSchema(db);
  const gcodeText = `; generated by PrusaSlicer 2.6
; filament used [g] = 12.5
G1 X0
`;
  const result = attachGcode(db, 1, 'C:/prints/benchy.gcode', {
    existsSync: () => true,
    readFileSync: () => gcodeText
  });
  assert.equal(result.ok, true);
  assert.equal(result.meta.filamentGrams, 12.5);
  const listed = listForModel(db, 1);
  assert.equal(listed.length, 1);
  assert.equal(listed[0].filePath, path.normalize('C:/prints/benchy.gcode'));
});

test('sendToPrinter uploads via Moonraker multipart', async () => {
  const { sendToPrinter } = require('./gcode-index');
  const calls = [];
  const fakeFetch = async (url, opts = {}) => {
    calls.push({ url, method: opts.method || 'GET', body: opts.body });
    if (String(url).endsWith('/server/info')) return { ok: true, status: 200 };
    return {
      ok: true,
      status: 200,
      json: async () => ({ item: { path: 'gcodes/a.gcode' } })
    };
  };
  const result = await sendToPrinter(
    { is_klipper: true, host: '192.168.1.50' },
    'C:/prints/a.gcode',
    {
      fetch: fakeFetch,
      readFile: async () => Buffer.from('G1 X0'),
      FormData: class {
        constructor() { this.parts = []; }
        append(k, v, name) { this.parts.push({ k, v, name }); }
      },
      Blob: class {
        constructor(parts) { this.parts = parts; }
      }
    }
  );
  assert.equal(result.ok, true);
  assert.ok(calls.some((c) => String(c.url).includes('/server/files/upload')));
});

